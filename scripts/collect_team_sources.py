"""Collect a bounded, provenance-preserving public teaming research corpus.

Award descriptions come verbatim from the frozen USAspending snapshot. Web
sources are extracted from the actual HTML main content, never generated by a
model. Vendor excerpts are deliberately short and remain self-reported claims.
"""

from __future__ import annotations

from collections import Counter
from datetime import datetime, timezone
import hashlib
from html.parser import HTMLParser
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
VOID_TAGS = {"area", "base", "br", "col", "embed", "hr", "img", "input", "link", "meta", "param", "source", "track", "wbr"}
SKIP_TAGS = {"script", "style", "noscript", "svg", "nav", "header", "footer", "form"}
AWARD_PATTERNS = (
    r"\bsoc\b", r"security operations", r"zero[ -]?trust", r"identity", r"access management",
    r"vulnerability", r"cyber[ -]?security support", r"network defense", r"cyber defense",
)
WEB_SOURCES = (
    {"id": "guidance_cisa_zero_trust_maturity_model", "kind": "agency_guidance",
     "title": "CISA — Zero Trust Maturity Model (official guidance page)",
     "url": "https://www.cisa.gov/resources-tools/resources/zero-trust-maturity-model",
     "start": None, "stop": "Resource Materials", "words": None, "user_agent": "Mozilla/5.0"},
    {"id": "capability_leidos_cyber", "kind": "company_capability",
     "title": "Leidos — Cyber Operations (self-reported capability excerpt)",
     "url": "https://www.leidos.com/capabilities/cyber",
     "start": "Defending what's next", "stop": None, "words": 185},
    {"id": "capability_guidepoint_iam", "kind": "company_capability",
     "title": "GuidePoint Security — Identity & Access Management (self-reported capability excerpt)",
     "url": "https://www.guidepointsecurity.com/identity-and-access-management/",
     "start": "Identity Security Capabilities", "stop": None, "words": 185},
)


class MainContentParser(HTMLParser):
    """Extract actual text in semantic main or known publisher content regions."""

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.stack: list[tuple[str, bool, bool]] = []
        self.parts: list[str] = []

    def handle_starttag(self, tag, attrs):
        attributes = dict(attrs)
        inherited_active = self.stack[-1][1] if self.stack else False
        inherited_skip = self.stack[-1][2] if self.stack else False
        active = inherited_active or tag == "main" or attributes.get("role") == "main" or attributes.get("data-swiftype-index") == "true"
        skip = inherited_skip or tag in SKIP_TAGS
        if tag not in VOID_TAGS:
            self.stack.append((tag, active, skip))

    def handle_startendtag(self, tag, attrs):
        pass

    def handle_endtag(self, tag):
        for index in range(len(self.stack) - 1, -1, -1):
            if self.stack[index][0] == tag:
                self.stack = self.stack[:index]
                break

    def handle_data(self, value):
        if self.stack and self.stack[-1][1] and not self.stack[-1][2]:
            text = " ".join(value.split())
            if text:
                self.parts.append(text)


def extract_main_text(html: str) -> str:
    parser = MainContentParser()
    parser.feed(html)
    result = "\n".join(parser.parts)
    if len(result) < 200:
        raise ValueError("Source has no usable main-content text; refusing to store navigation or a challenge page")
    return result


def bounded_excerpt(text: str, start: str | None, stop: str | None, words: int | None) -> str:
    if start:
        index = text.find(start)
        if index < 0:
            raise ValueError("Expected capability heading was not found; inspect the changed source page")
        text = text[index:]
    if stop:
        index = text.find(stop)
        if index < 0:
            raise ValueError("Expected guidance section boundary was not found")
        text = text[:index]
    if words:
        text = " ".join(text.split()[:words])
    return text.strip()


def select_awards(awards: list[dict], limit: int = 25) -> list[dict]:
    """Curated by description-only topic overlap, not recipient-name matches."""
    scored = [(sum(bool(re.search(pattern, a["description"], re.I)) for pattern in AWARD_PATTERNS), a) for a in awards]
    scored = [(score, a) for score, a in scored if score]
    scored.sort(key=lambda item: (-item[0], -item[1]["obligation"], item[1]["id"]))
    return [a for _, a in scored[:limit]]


def award_source(award: dict, retrieved_at: str) -> dict:
    text = "\n".join([
        f"Award ID: {award['award_id']}",
        f"USAspending generated award ID: {award['id']}",
        f"Awarding agency: {award['agency']}",
        f"Awarding subagency: {award.get('sub_agency') or 'not reported'}",
        f"Recipient name: {award['recipient_name']}",
        f"Recipient UEI: {award.get('recipient_uei') or 'not reported'}",
        f"Reported ultimate parent: {award.get('parent_name') or 'not reported'}",
        f"Reported parent UEI: {award.get('parent_uei') or 'not reported'}",
        f"Award-summary lifetime obligations (USD): {award['obligation']}",
        f"Period of performance start: {award.get('start_date') or 'not reported'}",
        f"Period of performance end: {award.get('end_date') or 'not reported'}",
        "Award description (verbatim source field):", award['description'],
    ])
    return {"id": "award_" + hashlib.sha256(award["id"].encode()).hexdigest()[:20],
            "title": f"{award['recipient_name']} — {award['award_id']}", "kind": "award",
            "url": award["source_url"], "retrieved_at": retrieved_at, "text": text,
            "notes": ["Historical public award record from the frozen DHS FY2025 cyber keyword slice; not an open solicitation.",
                      "Award summaries do not establish current contractor availability, teaming interest, project outcomes, or current opportunity requirements.",
                      "Financial value is lifetime award-summary obligations, not FY2025-only spending or cash paid.",
                      "Record labels are a deterministic rendering of source fields; the description is verbatim."]}


def web_source(spec: dict, html: str, retrieved_at: str) -> dict:
    text = bounded_excerpt(extract_main_text(html), spec["start"], spec["stop"], spec["words"])
    notes = ["Actual publicly retrieved HTML main-content text, whitespace normalized; not a model-generated summary."]
    if spec["kind"] == "company_capability":
        notes += ["Self-reported vendor capability claims; not independently verified past performance or eligibility.",
                  "A capability page does not establish willingness, availability, a teaming agreement, socioeconomic status, or a specific federal award relationship.",
                  f"Bounded excerpt: at most {spec['words']} words from the named capability section."]
    else:
        notes += ["Official agency guidance and planning context; not a live solicitation or procurement-specific statement of work.",
                  "This is the HTML overview page; it is not the full linked maturity-model PDF or a claim that every roadmap item is mandatory for a procurement."]
    return {key: spec[key] for key in ("id", "title", "kind", "url")} | {"retrieved_at": retrieved_at, "text": text, "notes": notes}


def validate_sources(sources: list[dict]) -> None:
    counts = Counter(s["kind"] for s in sources)
    if not 20 <= counts["award"] <= 35 or counts["agency_guidance"] < 1 or counts["company_capability"] < 2:
        raise ValueError("Corpus must include 20–35 awards, official guidance, and two vendor capability sources")
    if len({s["id"] for s in sources}) != len(sources):
        raise ValueError("Duplicate source IDs")
    for source in sources:
        if len(source["text"]) < 100 or not source.get("url") or not source.get("retrieved_at"):
            raise ValueError("Source content and provenance are required")
        if source["kind"] == "company_capability" and len(source["text"].split()) > 185:
            raise ValueError("Vendor excerpt exceeds its bounded text allowance")


def main():
    snapshot = json.loads((ROOT / "data/snapshot.json").read_text())
    selected = select_awards(snapshot["awards"])
    sources = [award_source(a, snapshot["metadata"]["retrieved_at"]) for a in selected]
    # CISA serves this public HTML page to curl but blocks Python HTTP clients.
    # No shell or credential-bearing arguments are involved. A non-2xx response
    # or changed/unusable content aborts before replacing the previous corpus.
    for spec in WEB_SOURCES:
        command = ["curl", "--fail", "--silent", "--show-error", "--location",
                   "--retry", "2", "--retry-all-errors", "--max-time", "45"]
        if spec.get("user_agent"):
            command += ["--user-agent", spec["user_agent"]]
        response = subprocess.run(command + [spec["url"]],
                                  capture_output=True, text=True, check=True)
        sources.append(web_source(spec, response.stdout, datetime.now(timezone.utc).isoformat()))
    validate_sources(sources)
    result = {"version": 1, "sources": sources, "notes": [
        "Curated market/teaming research corpus, not a live opportunity feed or a recommendation to transact.",
        "Award descriptions were selected by SOC, security operations, zero trust, identity/access, vulnerability, network defense, cyber defense, and cybersecurity-support wording; no relevance judgment is inferred from company names.",
        f"Historical awards originate from snapshot {snapshot['metadata']['snapshot_id']}.",
        "Agency guidance, historical awards, and self-reported company capabilities have different evidentiary roles; no open solicitation is asserted.",
        "Vendor excerpts are bounded and verbatim apart from whitespace normalization. The current source pages may change after collection.",
        "No internal brief is included as an external fact; demo/user research briefs are supplied separately at run time.",
    ]}
    output = ROOT / "data/team_sources.json"
    temporary = output.with_suffix(".tmp")
    temporary.write_text(json.dumps(result, indent=2, ensure_ascii=False, allow_nan=False) + "\n")
    temporary.replace(output)
    print(json.dumps({"path": str(output), "source_counts": dict(Counter(s["kind"] for s in sources))}))


if __name__ == "__main__":
    main()
